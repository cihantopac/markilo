#!/usr/bin/env node
// Bundles the Markilo CLI into a single dependency-free ESM file plus the resvg and PathKit WASM binaries.
// dist/ is committed so the Claude Code plugin works right after install, with no npm install step.
import { copyFileSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

// css-tree and csso read JSON through createRequire(import.meta.url), which a bundle cannot resolve.
// Rewrite those reads into static imports so the data is inlined.
const inlineJsonRequires = {
  name: 'inline-json-requires',
  setup(b) {
    b.onLoad({ filter: /[\\/](css-tree|csso)[\\/]lib[\\/].*\.js$/ }, async (args) => {
      let code = readFileSync(args.path, 'utf8');
      if (!code.includes('createRequire')) return undefined;
      const imports = [];
      code = code.replace(/require\(\s*['"]([^'"]+\.json)['"]\s*\)/g, (_, spec) => {
        const id = `__json${imports.length}`;
        imports.push(`import ${id} from ${JSON.stringify(spec)};`);
        return id;
      });
      return { contents: `${imports.join('\n')}\n${code}`, loader: 'js', resolveDir: dirname(args.path) };
    });
  },
};

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outdir = process.argv[2] ? resolve(process.cwd(), process.argv[2]) : join(root, 'plugin', 'dist');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

rmSync(outdir, { recursive: true, force: true });
mkdirSync(outdir, { recursive: true });

await build({
  entryPoints: [join(root, 'src/cli/main.ts')],
  outfile: join(outdir, 'markilo.mjs'),
  bundle: true,
  platform: 'node',
  target: 'node20',
  format: 'esm',
  minify: true,
  keepNames: true,
  legalComments: 'none',
  sourcemap: false,
  logLevel: 'warning',
  plugins: [inlineJsonRequires],
  define: { __MARKILO_VERSION__: JSON.stringify(pkg.version) },
  banner: {
    js: [
      '#!/usr/bin/env node',
      `// Markilo ${pkg.version} - generated by scripts/build.mjs. Do not edit; edit src/ instead.`,
      "import { createRequire as __markiloCreateRequire } from 'node:module';",
      'const require = __markiloCreateRequire(import.meta.url);',
      // pathkit-wasm (Emscripten) reads __dirname when it detects Node; ESM has none.
      "import { fileURLToPath as __markiloFileUrl } from 'node:url';",
      "const __filename = __markiloFileUrl(import.meta.url), __dirname = __markiloFileUrl(new URL('.', import.meta.url));",
    ].join('\n'),
  },
});
copyFileSync(join(root, 'node_modules/@resvg/resvg-wasm/index_bg.wasm'), join(outdir, 'resvg.wasm'));
copyFileSync(join(root, 'node_modules/pathkit-wasm/bin/pathkit.wasm'), join(outdir, 'pathkit.wasm'));
console.log(`Built ${outdir}/markilo.mjs`);
