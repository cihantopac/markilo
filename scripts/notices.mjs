#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md for everything bundled into dist/ and fonts/.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const BUNDLED = ['@resvg/resvg-wasm', 'svgo', 'fontkit', 'pngjs', 'jpeg-js'];
const seen = new Map();
function walk(name) {
  if (seen.has(name)) return;
  let p;
  try {
    p = JSON.parse(readFileSync(join(root, 'node_modules', name, 'package.json'), 'utf8'));
  } catch {
    return;
  }
  const repo = typeof p.repository === 'string' ? p.repository : (p.repository?.url ?? '');
  seen.set(name, {
    version: p.version,
    license: p.license ?? 'see package',
    repo: repo.replace(/^git\+/, '').replace(/\.git$/, ''),
  });
  for (const d of Object.keys(p.dependencies ?? {})) walk(d);
}
BUNDLED.forEach(walk);
const fonts = JSON.parse(readFileSync(join(root, 'plugin/fonts/fonts.json'), 'utf8')).families;
const lines = [
  '# Third-party notices',
  '',
  'Markilo is licensed under Apache-2.0. The distributed plugin also contains the components below,',
  'each under its own license. Generated by `scripts/notices.mjs`.',
  '',
  '## Fonts (`plugin/fonts/`)',
  '',
  '| Family | License | Source |',
  '| --- | --- | --- |',
  ...fonts.map((f) => `| ${f.family} | SIL OFL 1.1 (\`plugin/fonts/${f.licenseFile}\`) | ${f.source} |`),
  '',
  '## Bundled into `plugin/dist/markilo.mjs` and `plugin/dist/resvg.wasm`',
  '',
  '| Package | Version | License | Repository |',
  '| --- | --- | --- | --- |',
  ...[...seen.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([n, i]) => `| ${n} | ${i.version} | ${i.license} | ${i.repo} |`),
  '',
];
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
writeFileSync(join(root, 'plugin', 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
console.log(`THIRD_PARTY_NOTICES.md: ${seen.size} packages, ${fonts.length} font families`);
