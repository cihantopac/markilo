import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MarkiloError } from '../core/errors.js';
import { writeFileSafe } from '../core/fsx.js';
import { resolveInsideReal } from '../core/paths.js';

/**
 * Claude Code is Markilo's home (skills, sub-agents, permissions), but nothing in Markilo needs Claude: the toolchain
 * is a plain CLI and the three roles are instructions. This writes the same workflow for other coding agents — the
 * orchestrating instructions (an AGENTS.md section for Codex, a Cursor rule, a VS Code custom agent, or MARKILO.md)
 * and, where the agent supports them, the three roles as sub-agents with their own context and model.
 */

export const AGENT_TARGETS = ['codex', 'cursor', 'vscode', 'generic'] as const;
export type AgentTarget = (typeof AGENT_TARGETS)[number];

/**
 * Markilo's roles and what each asks of a model. The Claude Code plugin pins them in the agents' frontmatter
 * (researcher and designer on Sonnet, critic on Opus); elsewhere the user names models with `--model role=<id>`.
 */
export const ROLES = {
  researcher: {
    source: 'brand-researcher',
    claude: 'sonnet',
    needs: 'web search and reading pages; a fast general model is enough',
  },
  designer: {
    source: 'concept-designer',
    claude: 'sonnet',
    needs:
      "a shell, file editing and looking at PNGs; a capable general model (in Markilo's benchmark a stronger designer model did not design better)",
  },
  critic: {
    source: 'design-critic',
    claude: 'opus',
    needs: 'image input and a fresh context; your strongest model, at high reasoning effort',
  },
} as const;
export type Role = keyof typeof ROLES;
export const ROLE_IDS = Object.keys(ROLES) as Role[];

const START = '<!-- markilo:start -->';
const END = '<!-- markilo:end -->';
const MARK = 'markilo agent-setup';

/** The running CLI, the plugin folder around it and its reference docs (dist/ → ../skills/design/references). */
export function locateToolchain(): { cli: string; references: string; root: string } {
  const here = dirname(fileURLToPath(import.meta.url));
  // Bundled: dist/markilo.mjs next to this code. From a source checkout: the repository's plugin/dist bundle.
  const cli =
    [join(here, 'markilo.mjs'), resolve(here, '..', '..', 'plugin', 'dist', 'markilo.mjs')].find((p) =>
      existsSync(p),
    ) ?? resolve(process.argv[1] ?? 'markilo.mjs');
  const roots = [resolve(dirname(cli), '..'), resolve(here, '..', '..', 'plugin')];
  const root = roots.find((r) => existsSync(join(r, 'agents'))) ?? roots[0]!;
  return { cli, references: join(root, 'skills', 'design', 'references'), root };
}

/** The sub-agent name a target's orchestrator calls (Codex agent names are identifiers). */
export const agentName = (target: AgentTarget, role: Role) =>
  target === 'codex' ? `markilo_${role}` : `markilo-${role}`;

const usesSubagents = (target: AgentTarget) => target !== 'generic';

export function agentGuide(target: AgentTarget, cli: string, refs: string, command?: string): string {
  const m = command ?? `node "${cli}"`;
  const ref = (f: string) => `${refs}/${f}`.replace(/\\/g, '/');
  const n = (r: Role) => `\`${agentName(target, r)}\``;
  const what = target === 'cursor' ? 'This rule' : target === 'vscode' ? 'This agent' : 'This section';
  return `# Markilo — brand identity studio

Use Markilo when the user asks for a logo, brand identity, icon set or brand refresh. Markilo is a deterministic
toolchain: you run its commands, read their JSON output and look at the images it renders. ${what} was generated by \`markilo agent-setup --target ${target}\`.

Run: \`${m} <command>\` (JSON output; \`${m} help\` lists every command; details in ${ref('cli.md')}).

## Who does what
${
  usesSubagents(target)
    ? `Run the design work in ${n('designer')} — one run creates a round's three proposals, another develops the one the
user chooses — and the final critique in ${n('critic')}, each in its own context. Research runs in ${n('researcher')}
only for a broad brief. Give each sub-agent the brand slug, the concept id, the stage and what the user decided.`
    : `Run the final critique as a separate, deliberately critical pass — ideally a fresh chat that reads images —
starting with a cold look at the rendered sheets, before reading the rationale.`
}
Models: design and research run well on a capable general model; the critic benefits from your strongest model that
reads images. The user, not the critic, decides which concept to develop and approve.

## Rules
1. The user owns the creative choice: show proposals and let them choose; \`finalize\` needs
   \`--user-choice "<their words>"\`.
2. Measured vs judged: measurements (contrast, legibility, similarity, sizes) come from the toolchain; your own
   opinions are labelled as judgment with a reason.
3. Never invent facts about a product, market, competitor, trademark or user. Record what you could not establish with
   \`${m} profile add-gap\`.
4. Ask the user before network use (commands need \`--allow-network\`), web searches with private names, copying
   assets into their project (\`install-assets --apply\`) or anything that costs money.
5. Locked brands are never redesigned, recolored or "improved".
6. Originality is mandatory: a concept with verdict \`redesign\` is redrawn from the idea up. "No conflicts found" is
   never proof of availability; trademark clearance needs a lawyer.
7. Look at your work: render every SVG you write and open the PNG before showing it.
8. Spend deliberately: \`${m} cost --brand <slug>\` before each agent or round, record each phase after it; at
   \`status: over\` stop and ask.

## Workflow (say which stage you are in): Understand → Explore → Choose → Develop → Verify → Export
1. Understand: \`${m} init\`, \`${m} brand add "<Name>"\`; for a repository \`${m} research repo <path> --brand <slug>\`
   (monorepo: \`research monorepo\` first); for a site, with permission, \`research site <url> --brand <slug> --allow-network\`.
   Read the README and the product's interface (its colours and type are equity). Competitors once, about five, only
   with network approval (\`research competitors\`). Brief: \`${m} brief update --brand <slug> --file …\` with the
   stance (what the identity should feel like and must not). Ask at most three questions, plus an optional one for
   references the user likes or dislikes (\`reference add --category inspiration|dislike|existing\`).
2. Explore: exactly three genuinely different proposals in one designer run (\`concept new … --round 1\`, at least
   one \`--lead wordmark\`), each with \`wordmark.svg\`, a compact icon \`symbol.svg\`, and
   \`concept update --idea … --strengths … --weaknesses …\`; then \`${m} proposals --brand <slug>\`. How to design them:
   ${ref('design-principles.md')} (freeform SVG and custom letterforms are first-class; construction specs are an
   optional tool: ${ref('construction.md')}). No critic at this stage.
3. Choose: \`${m} gallery --serve\` (keep it running in the background; give the user the URL), then
   \`${m} feedback --brand <slug>\`: select, change, combine, or reject the round. At most two rounds on your own;
   a third needs \`--round 3 --directed "<their words>"\`.
4. Develop the chosen concept (letterforms, spacing, optical balance, icon and small version, lockups, colour), then
   \`${m} verify\` until nothing fails. SVG rules: ${ref('svg-authoring.md')}.
5. Verify: one independent critique (cold first: \`concept update --reads-as … --blind … --present yes|no:reason\`,
   then \`--judgment criterion=score:reason\` and up to five concrete craft fixes). It is advice; apply the fixes once.
6. Deliver, on the user's approval: \`finalize --user-choice "<their words>"\` (\`--accept-risk\` only when the user
   accepts an insufficient-evidence verdict), \`deliverables\`, \`export\`, then
   \`install-assets --framework auto --brand <slug>\` as a dry run, and \`--apply\` only with the user's OK.

Originality policy: ${ref('originality.md')}. Stage gates: ${ref('workflow.md')}.
`;
}

export interface AgentFile {
  file: string;
  action: 'create' | 'update' | 'unchanged';
  /** The role's sub-agent, for sub-agent files. */
  role?: Role;
  /** The model the file pins; without one the sub-agent runs on the chat's model. */
  model?: string | string[];
}

export interface AgentSetupResult {
  target: AgentTarget;
  file: string;
  action: 'create' | 'update-section' | 'append-section' | 'unchanged';
  applied: boolean;
  content: string;
  /** The roles as sub-agents (Codex, Cursor, VS Code). */
  agents: AgentFile[];
  /** What each role runs on, and what it needs from a model. */
  models: Record<Role, { model: string | string[]; needs: string }>;
  /** Set when the files name paths on this machine (they reveal the user name if they are committed). */
  warning?: string;
}

/**
 * A role's instructions for another agent, from the plugin's own agent file: the same procedure, with the Claude Code
 * specifics (plugin paths, its permission rules, its Read tool) replaced by the CLI command and plain paths.
 */
/** How the plugin's own files name its folder (Claude Code expands it). */
const PLUGIN_ROOT = ['$', '{CLAUDE_PLUGIN_ROOT}'].join('');

export function portableInstructions(
  role: Role,
  opts: { command: string; references: string; root: string },
): string {
  const md = readFileSync(join(opts.root, 'agents', `${ROLES[role].source}.md`), 'utf8');
  const refs = opts.references.replace(/\\/g, '/');
  const root = opts.root.replace(/\\/g, '/');
  const body = md
    .replace(/^---[\s\S]*?\n---\n/, '')
    .trim()
    .replace(
      /Toolchain: `node "\$\{CLAUDE_PLUGIN_ROOT\}\/dist\/markilo\.mjs" <command>` \(written `markilo`\)\.[^\n]*?permission prompts\./,
      `Toolchain: \`${opts.command} <command>\` (written \`markilo\` below; it prints JSON).`,
    )
    .replaceAll(`${PLUGIN_ROOT}/skills/design/references/`, `${refs}/`)
    .replaceAll(`${PLUGIN_ROOT}/`, `${root}/`)
    .replace(/`Read`(\s)/g, 'Open$1');
  return `${body}

Look at every PNG as an image (open the file with your image or file tool), never through its bytes or the SVG
source.`;
}

const DESCRIPTIONS: Record<Role, string> = {
  researcher:
    "Markilo's brand researcher: market, audience, competitors and their marks, recorded as sourced findings in the Markilo workspace.",
  designer:
    "Markilo's concept designer: three genuinely different identity proposals per round, then the user's chosen one developed into a verified wordmark, icon and lockups.",
  critic:
    "Markilo's independent design critic: a cold read of the developed identity from the rendered PNGs, with scores and concrete craft fixes — advice, never a gate on the user's choice. Run it in its own context.",
};

function subagentFile(
  target: AgentTarget,
  role: Role,
  body: string,
  model: string[] | undefined,
): { rel: string; content: string } {
  const name = agentName(target, role);
  const stamp = `Generated by ${MARK} --target ${target}; rerun it to update.`;
  const q = (v: string) => JSON.stringify(v);
  if (target === 'codex')
    return {
      rel: `.codex/agents/markilo-${role}.toml`,
      content: [
        `# ${stamp}`,
        `name = ${q(name)}`,
        `description = ${q(DESCRIPTIONS[role])}`,
        ...(model ? [`model = ${q(model[0]!)}`] : []),
        ...(role === 'critic' ? ['model_reasoning_effort = "high"'] : []),
        // A TOML literal string: nothing inside is escaped.
        `developer_instructions = '''\n${body.replaceAll("'''", "''’")}\n'''`,
        '',
      ].join('\n'),
    };
  const modelLine =
    target === 'cursor'
      ? [`model: ${model ? model[0] : 'inherit'}`]
      : model
        ? [`model: ${model.length > 1 ? `[${model.map(q).join(', ')}]` : q(model[0]!)}`]
        : [];
  const front = [
    '---',
    `name: ${name}`,
    `description: ${q(DESCRIPTIONS[role])}`,
    ...modelLine,
    ...(target === 'vscode' ? ['user-invocable: false'] : []),
    '---',
  ].join('\n');
  return {
    rel:
      target === 'cursor' ? `.cursor/agents/markilo-${role}.md` : `.github/agents/markilo-${role}.agent.md`,
    content: `${front}\n\n<!-- ${stamp} -->\n\n${body}\n`,
  };
}

/** create, update or unchanged for a file Markilo owns; a same-named file it did not write is refused. */
function ownedAction(path: string, rel: string, content: string, force?: boolean): AgentFile['action'] {
  if (!existsSync(path)) return 'create';
  const current = readFileSync(path, 'utf8');
  // A file of the same name that Markilo did not write is the user's: never replace it silently.
  if (!current.includes(MARK) && !force)
    throw new MarkiloError(
      'EXISTS',
      `${rel} exists and was not written by Markilo.`,
      'Pass --force to replace it.',
    );
  return current === content ? 'unchanged' : 'update';
}

export function agentSetup(
  project: string,
  target: AgentTarget,
  opts: {
    apply?: boolean;
    force?: boolean;
    command?: string;
    references?: string;
    /** role → model ids; more than one is a preference order where the agent supports it (VS Code). */
    models?: Partial<Record<Role, string[]>>;
  } = {},
): AgentSetupResult {
  if (!(AGENT_TARGETS as readonly string[]).includes(target))
    throw new MarkiloError('USAGE', `--target must be one of ${AGENT_TARGETS.join(', ')}.`);
  const located = locateToolchain();
  const references = opts.references ?? located.references;
  const command = opts.command ?? `node "${located.cli}"`;
  const guide = agentGuide(target, located.cli, references, opts.command);
  const rel = {
    codex: 'AGENTS.md',
    cursor: '.cursor/rules/markilo.mdc',
    vscode: '.github/agents/markilo.agent.md',
    generic: 'MARKILO.md',
  }[target];
  const path = resolveInsideReal(project, rel);
  let content: string;
  let action: AgentSetupResult['action'];
  if (target === 'codex') {
    // AGENTS.md belongs to the project: only Markilo's own marked section is added or replaced.
    const block = `${START}\n${guide}${END}\n`;
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const i = current.indexOf(START);
    const j = current.indexOf(END);
    if (i >= 0 && j > i) {
      content = `${current.slice(0, i)}${block}${current.slice(j + END.length).replace(/^\n/, '')}`;
      action = content === current ? 'unchanged' : 'update-section';
    } else {
      content = current ? `${current.replace(/\n*$/, '\n\n')}${block}` : block;
      action = current ? 'append-section' : 'create';
    }
  } else {
    const desc =
      'Markilo brand identity studio — research, design, verify and export brand identities with the Markilo CLI';
    content =
      target === 'cursor'
        ? `---\ndescription: ${desc}\nglobs:\nalwaysApply: false\n---\n\n${guide}`
        : target === 'vscode'
          ? `---\nname: markilo\ndescription: ${desc}\n---\n\n${guide}`
          : guide;
    const owned = ownedAction(path, rel, content, opts.force);
    action = owned === 'update' ? 'update-section' : owned;
  }
  const agents: (AgentFile & { path: string; content: string })[] = [];
  if (usesSubagents(target))
    for (const role of ROLE_IDS) {
      const model = opts.models?.[role];
      const f = subagentFile(
        target,
        role,
        portableInstructions(role, { command, references, root: located.root }),
        model,
      );
      const p = resolveInsideReal(project, f.rel);
      agents.push({
        role,
        file: f.rel,
        action: ownedAction(p, f.rel, f.content, opts.force),
        ...(model ? { model: target === 'vscode' && model.length > 1 ? model : model[0]! } : {}),
        path: p,
        content: f.content,
      });
    }
  if (opts.apply) {
    if (action !== 'unchanged') writeFileSafe(path, content, { force: true });
    for (const a of agents) if (a.action !== 'unchanged') writeFileSafe(a.path, a.content, { force: true });
  }
  const models = Object.fromEntries(
    ROLE_IDS.map((r) => [
      r,
      {
        model: agents.find((x) => x.role === r)?.model ?? 'inherits the chat model',
        needs: ROLES[r].needs,
      },
    ]),
  ) as AgentSetupResult['models'];
  const local = !opts.command || !opts.references;
  return {
    target,
    file: rel,
    action,
    applied: Boolean(opts.apply) && (action !== 'unchanged' || agents.some((a) => a.action !== 'unchanged')),
    content,
    agents: agents.map(({ path: _p, content: _c, ...a }) => a),
    models,
    ...(local
      ? {
          warning:
            'The files contain paths on this computer. Before committing them to a shared repository, pass --cli "<command>" and --references "<path>" that work for everyone (for example `npx markilo` and node_modules/markilo/plugin/skills/design/references).',
        }
      : {}),
  };
}
