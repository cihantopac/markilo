import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { MarkiloError } from '../core/errors.js';
import { writeFileSafe } from '../core/fsx.js';
import { resolveInsideReal } from '../core/paths.js';

/**
 * Claude Code is Markilo's home (skills, sub-agents, permissions). Other coding agents can run the same CLI with the
 * same workflow and rules; this writes their instruction file: AGENTS.md for Codex (and other AGENTS.md readers),
 * a Cursor project rule, or a plain MARKILO.md.
 */

export const AGENT_TARGETS = ['codex', 'cursor', 'generic'] as const;
export type AgentTarget = (typeof AGENT_TARGETS)[number];

const START = '<!-- markilo:start -->';
const END = '<!-- markilo:end -->';

/** The running CLI and the plugin's reference docs next to it (dist/ → ../skills/design/references). */
export function locateToolchain(): { cli: string; references: string } {
  const here = dirname(fileURLToPath(import.meta.url));
  // Bundled: dist/markilo.mjs next to this code. From a source checkout: the repository's plugin/dist bundle.
  const cli =
    [join(here, 'markilo.mjs'), resolve(here, '..', '..', 'plugin', 'dist', 'markilo.mjs')].find((p) =>
      existsSync(p),
    ) ?? resolve(process.argv[1] ?? 'markilo.mjs');
  const candidates = [
    join(dirname(cli), '..', 'skills', 'design', 'references'),
    resolve(here, '..', '..', 'plugin', 'skills', 'design', 'references'),
  ];
  return { cli, references: candidates.find((c) => existsSync(c)) ?? candidates[0]! };
}

export function agentGuide(target: AgentTarget, cli: string, refs: string, command?: string): string {
  const m = command ?? `node "${cli}"`;
  const ref = (f: string) => `${refs}/${f}`.replace(/\\/g, '/');
  return `# Markilo — brand identity studio

Use Markilo when the user asks for a logo, brand identity, icon set or brand refresh. Markilo is a deterministic
toolchain: you run its commands, read their JSON output and look at the images it renders. ${target === 'cursor' ? 'This rule' : 'This section'} was generated by \`markilo agent-setup --target ${target}\`.

Run: \`${m} <command>\` (JSON output; \`${m} help\` lists every command; details in ${ref('cli.md')}).

## Rules
1. Measured vs judged: measurements (contrast, legibility, similarity, sizes) come from the toolchain; your own
   opinions are labelled as judgment with a reason.
2. Never invent facts about a product, market, competitor, trademark or user. Record what you could not establish with
   \`${m} profile add-gap\`.
3. Ask the user before network use (commands need \`--allow-network\`), web searches with private names, copying
   assets into their project (\`install-assets --apply\`) or anything that costs money.
4. Locked brands are never redesigned, recolored or "improved".
5. Originality is mandatory: a concept with verdict \`redesign\` is reworked from the idea up. "No conflicts found" is
   never proof of availability; trademark clearance needs a lawyer.
6. Look at your work: after every change run \`${m} verify\` and open the PNGs it writes (review sheet, context sheet).

## Workflow (say which stage you are in)
1. Discover: \`${m} init\`, \`${m} brand add "<Name>"\`; for a repository \`${m} research repo <path> --brand <slug>\`
   (monorepo: \`research monorepo\` first); for a site, with permission, \`research site <url> --brand <slug> --allow-network\`.
2. Research: \`${m} profile understanding --brand <slug>\` (stated vs inferred facts, unknowns); competitors with
   \`research competitors\` and \`reference add\`; \`reference dedupe\`. Playbook: ${ref('research-playbook.md')}.
3. Brief: \`${m} brief update --brand <slug> --file …\`; ask only what you cannot infer, 2–5 questions at once.
4. Explore: 3–5 genuinely different directions (idea, metaphor, form, type, color, risks); at most one built on the
   name's initial, at least one with no letter and no product object; \`concept new\` for each.
5. Sketch: 3–5 construction specs per direction in \`concepts/<id>/sketches/\`, each with an "idea";
   \`${m} sketches --brand <slug> --concept <id>\`. Build marks only with construction specs: ${ref('construction.md')}.
6. Sketch review: as a separate, critical pass, open each \`sketches/board.png\`, strike sketches that read as a UI
   icon, a known logo, a cliché, the product's own object or the name's initial with a cut, and develop the strongest
   one left per direction (\`concept update --sketch-pick sN|none\`; none only when every sketch is struck).
7. Develop: tune with \`construct … --vary\`, commit with \`construct … --brand --concept --set …\`, wordmark
   (\`wordmark\` or a constructed one), \`verify\`. Principles: ${ref('design-principles.md')}; SVG rules: ${ref('svg-authoring.md')}.
8. Critique (a separate pass, as an independent critic). Cold first: read the brief and look only at
   \`research/cache/review/context-<id>.png\` and the review sheet; record what the mark looks like
   (\`concept update --reads-as "…; …; …"\`), blind scores (\`--blind distinctiveness=n,memorability=n,brand-fit=n,craft=n,versatility=n\`)
   and whether a senior designer would present it as is (\`--present yes|no:reason\`). Then read the rationale and
   reports and add feedback scores with \`--judgment criterion=score:reason\` (brand-fit, semantic-relevance,
   distinctiveness, memorability, simplicity, balance, craft, typography, color, cultural-fit, timelessness,
   premium-perception, versatility); a measured problem may turn the yes into a no, never the other way. Gate: blind
   brand-fit, distinctiveness and memorability ≥ 6 and yes — \`${m} concept list\` shows it; otherwise rework (max 2
   rounds) or reject.
9. Review: \`${m} gallery --serve\` (keep it running in the background; give the user the URL), then
   \`${m} feedback --brand <slug>\` to read their decisions, pins and preference.
10. Deliver: \`finalize\` (\`--accept-risk\` only when the user accepts an insufficient-evidence verdict; a concept that
    failed the gate needs \`--user-choice "<the user's reason>"\`),
    \`deliverables\`, \`export\`, then \`install-assets --framework auto --brand <slug>\` as a dry run, and \`--apply\` only
    with the user's OK.

Originality policy: ${ref('originality.md')}. Stage gates: ${ref('workflow.md')}.
`;
}

export interface AgentSetupResult {
  target: AgentTarget;
  file: string;
  action: 'create' | 'update-section' | 'append-section' | 'unchanged';
  applied: boolean;
  content: string;
  /** Set when the file names paths on this machine (they reveal the user name if the file is committed). */
  warning?: string;
}

export function agentSetup(
  project: string,
  target: AgentTarget,
  opts: { apply?: boolean; force?: boolean; command?: string; references?: string } = {},
): AgentSetupResult {
  if (!(AGENT_TARGETS as readonly string[]).includes(target))
    throw new MarkiloError('USAGE', `--target must be one of ${AGENT_TARGETS.join(', ')}.`);
  const located = locateToolchain();
  const references = opts.references ?? located.references;
  const guide = agentGuide(target, located.cli, references, opts.command);
  const rel =
    target === 'codex' ? 'AGENTS.md' : target === 'cursor' ? '.cursor/rules/markilo.mdc' : 'MARKILO.md';
  const path = resolveInsideReal(project, rel);
  let content: string;
  let action: AgentSetupResult['action'];
  if (target === 'codex') {
    // AGENTS.md belongs to the project: only Markilo's own marked section is added or replaced.
    const block = `${START}\n${guide}${END}\n`;
    const current = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const i = current.indexOf(START);
    const j = current.indexOf(END);
    if (i >= 0 && j > i) {
      content = `${current.slice(0, i)}${block}${current.slice(j + END.length).replace(/^\n/, '')}`;
      action = content === current ? 'unchanged' : 'update-section';
    } else {
      content = current ? `${current.replace(/\n*$/, '\n\n')}${block}` : block;
      action = current ? 'append-section' : 'create';
    }
  } else {
    content =
      target === 'cursor'
        ? `---\ndescription: Markilo brand identity studio — research, design, verify and export brand identities with the Markilo CLI\nglobs:\nalwaysApply: false\n---\n\n${guide}`
        : guide;
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
    // A file of the same name that Markilo did not write is the user's: never replace it silently.
    if (current !== undefined && !current.includes('markilo agent-setup') && !opts.force)
      throw new MarkiloError(
        'EXISTS',
        `${rel} exists and was not written by Markilo.`,
        'Pass --force to replace it.',
      );
    action = current === undefined ? 'create' : current === content ? 'unchanged' : 'update-section';
  }
  if (opts.apply && action !== 'unchanged') writeFileSafe(path, content, { force: true });
  const local = !opts.command || !opts.references;
  return {
    target,
    file: rel,
    action,
    applied: Boolean(opts.apply) && action !== 'unchanged',
    content,
    ...(local
      ? {
          warning:
            'The file contains paths on this computer. Before committing it to a shared repository, pass --cli "<command>" and --references "<path>" that work for everyone (for example a path inside the repository).',
        }
      : {}),
  };
}
