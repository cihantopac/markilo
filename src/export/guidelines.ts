import { contrastRatio, wcagRating } from '../analyze/color.js';
import type { Palette } from '../design/palette.js';
import { nestSvg, svgDocument } from '../svg/compose.js';
import { escapeText } from '../svg/xml.js';
import type { BrandKit } from './kit.js';
import { groundsFor } from './variants.js';

export interface GuidelinesInput {
  kit: BrandKit;
  palette: Palette;
  symbol: string | undefined;
  wordmark: string | undefined;
  lockupH: string | undefined;
  lockupS: string | undefined;
  reversed: (svg: string) => string;
}

const DONTS = [
  'Do not stretch, squash, skew or rotate the logo.',
  'Do not recolor outside the approved palette or apply gradients, shadows, glows or outlines.',
  'Do not rebuild the wordmark in another typeface or change its letter spacing.',
  'Do not rearrange the symbol and wordmark or change their size relationship.',
  'Do not place the logo on busy images or backgrounds with less than 3:1 contrast.',
  'Do not crop the symbol or place it inside another shape unless it is an approved appmark.',
];

function colorRows(k: BrandKit) {
  const entries: [string, string][] = [['Primary', k.palette.primary]];
  if (k.palette.secondary) entries.push(['Secondary', k.palette.secondary]);
  if (k.palette.accent) entries.push(['Accent', k.palette.accent]);
  entries.push(['Ink', k.palette.ink], ['Paper', k.palette.paper]);
  return entries.map(([name, hex]) => ({
    name,
    hex,
    onWhite: contrastRatio(hex, '#ffffff'),
    onDark: contrastRatio(hex, k.palette.dark),
  }));
}

export function guidelinesMarkdown(g: GuidelinesInput): string {
  const { kit } = g;
  const L: string[] = [];
  L.push(`# ${kit.name} brand guidelines`, '');
  if (kit.locked)
    L.push(
      '> This identity is **locked**: it is reproduced exactly as provided. Do not modify the artwork.',
      '',
    );
  L.push('## Logo files', '');
  L.push('| Use | File |', '| --- | --- |');
  if (g.lockupH) L.push('| Primary logo (default) | `logos/primary/primary-color.svg` |');
  if (g.lockupS) L.push('| Secondary logo (square-ish spaces) | `logos/secondary/secondary-color.svg` |');
  if (g.symbol) L.push('| Symbol (favicons, avatars, small spaces) | `logos/symbol/symbol-color.svg` |');
  if (g.wordmark)
    L.push('| Wordmark (when the symbol is shown nearby) | `logos/wordmark/wordmark-color.svg` |');
  if (!kit.locked)
    L.push(
      '| On dark backgrounds | `*-reversed.svg` |',
      '| One-color | `*-black.svg`, `*-white.svg`, `*-ink.svg` |',
    );
  L.push('');
  L.push('## Clear space and minimum size', '');
  L.push(
    '- Keep clear space on all sides equal to the cap height of the wordmark (the height of a capital letter).',
  );
  L.push(
    '- Minimum sizes: symbol 16 px on screen / 5 mm in print; horizontal logo 96 px wide on screen / 25 mm in print.',
  );
  L.push('- Use the compact lockup below 120 px width.', '');
  L.push('## Color', '');
  L.push('| Color | Hex | On white | On dark |', '| --- | --- | --- | --- |');
  for (const r of colorRows(kit))
    L.push(
      `| ${r.name} | \`${r.hex}\` | ${r.onWhite.toFixed(2)}:1 (${wcagRating(r.onWhite)}) | ${r.onDark.toFixed(2)}:1 (${wcagRating(r.onDark)}) |`,
    );
  L.push('', 'Full tonal scales are in `tokens/tokens.json` and `tokens/tokens.css`.', '');
  L.push(
    '### Accessible pairings',
    '',
    '| Foreground | Background | Ratio | WCAG | Use |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const p of g.palette.pairs)
    L.push(`| \`${p.foreground}\` | \`${p.background}\` | ${p.ratio}:1 | ${p.rating} | ${p.use} |`);
  for (const w of g.palette.warnings) L.push('', `> ⚠️ ${w}`);
  L.push('', '## Typography', '');
  if (kit.typography) {
    L.push(
      `- Brand typeface: **${kit.typography.family ?? kit.typography.fontId}**, weight ${kit.typography.weight}.`,
    );
    L.push(
      `- License: ${kit.typography.license ?? 'see fonts/ license file'}. The wordmark is outlined, so using the logo never requires the font.`,
    );
  } else L.push('- No brand typeface recorded. The wordmark is outlined artwork.');
  if (kit.originality) {
    L.push('', '## Originality check', '');
    L.push(
      `Approved with originality verdict **${kit.originality.verdict}** (confidence ${kit.originality.confidence})${kit.originality.acceptedRisk ? ', with the remaining risk explicitly accepted' : ''}. See \`${kit.originality.report}\`.`,
    );
    for (const line of evidenceLines(kit)) L.push('', line);
  }
  if (kit.notes?.length) L.push('', '## Usage notes', '', ...kit.notes.map((n) => `- ${n}`));
  L.push('', '## Do not', '', ...DONTS.map((d) => `- ${d}`), '');
  L.push(
    '---',
    '',
    `Generated by Markilo on ${new Date().toISOString().slice(0, 10)}${kit.concept ? ` from concept \`${kit.concept}\`` : ''}.`,
    '',
  );
  return L.join('\n');
}

function figure(svg: string | undefined, bg: string, w = 360, h = 160): string {
  if (!svg) return '';
  return svgDocument(w, h, nestSvg(svg, { x: w * 0.12, y: h * 0.18, width: w * 0.76, height: h * 0.64 }), {
    background: bg,
  });
}

/** Plain statements of what the originality verdict rests on; the registry sentence is never softened. */
function evidenceLines(kit: BrandKit): string[] {
  const e = kit.originality?.evidence;
  const out: string[] = [];
  if (e) out.push(`Compared against: ${e.visual}.`);
  if (!e || e.registryCoverage === 'none')
    out.push(
      'No trademark registry search was done (WIPO Global Brand Database, TMview, national registers). Search them, or have a trademark attorney do it, before registering or launching widely.',
    );
  else
    out.push(
      `Registry searches logged: ${e.registry}. Markilo's checks are still not a trademark clearance; have a trademark attorney confirm before registering.`,
    );
  return out;
}

export function guidelinesHtml(g: GuidelinesInput): string {
  const gr = groundsFor(g.kit.palette.paper, g.kit.palette.dark);
  const { kit } = g;
  const primary = g.lockupH ?? g.wordmark ?? g.symbol;
  const swatches = colorRows(kit)
    .map(
      (r) =>
        `<div class="sw"><div class="chip" style="background:${r.hex}"></div><b>${r.name}</b><code>${r.hex}</code><small>${r.onWhite.toFixed(1)}:1 on white · ${r.onDark.toFixed(1)}:1 on dark</small></div>`,
    )
    .join('');
  const scales = Object.entries(g.palette.scales)
    .map(
      ([name, s]) =>
        `<div class="scale"><span>${name}</span>${Object.entries(s.scale)
          .map(([k, v]) => `<i style="background:${v}" title="${k} ${v}"></i>`)
          .join('')}</div>`,
    )
    .join('');
  return `<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>${escapeText(kit.name)} — brand guidelines</title>
<style>
:root{--ink:${kit.palette.ink};--paper:${kit.palette.paper};--brand:${kit.palette.primary};--line:#e3e5ea}
*{box-sizing:border-box}body{margin:0;font:16px/1.55 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;color:var(--ink);background:var(--paper)}
main{max-width:1040px;margin:0 auto;padding:48px 24px}h1{font-size:40px;margin:0 0 8px}h2{margin-top:48px;border-top:1px solid var(--line);padding-top:24px}
.grid{display:grid;grid-template-columns:repeat(auto-fill,minmax(300px,1fr));gap:16px}.grid svg{width:100%;height:auto;border-radius:12px;border:1px solid var(--line)}
.sw{display:grid;gap:2px}.chip{height:72px;border-radius:10px;border:1px solid var(--line)}code{font-size:13px}small{color:#6b7080}
.swatches{display:grid;grid-template-columns:repeat(auto-fill,minmax(160px,1fr));gap:16px}.scale{display:flex;align-items:center;gap:4px;margin:6px 0}.scale span{width:90px}.scale i{flex:1;height:32px;border-radius:4px}
ul.dont li{margin:4px 0}.locked{padding:12px 16px;border-radius:10px;background:#fff6db;border:1px solid #f0d27a}
@media (max-width:600px){h1{font-size:30px}}
</style></head><body><main>
<h1>${escapeText(kit.name)}</h1><p>Brand guidelines${kit.concept ? ` · concept <code>${escapeText(kit.concept)}</code>` : ''} · generated ${new Date().toISOString().slice(0, 10)}</p>
${kit.locked ? '<p class="locked">This identity is locked and reproduced exactly as provided.</p>' : ''}
<h2>Logo</h2><div class="grid">${figure(primary, gr.native)}${kit.locked || !primary ? '' : figure(g.reversed(primary), gr.opposite)}${figure(g.lockupS, gr.native)}${figure(g.symbol, gr.native, 160, 160)}</div>
<h2>Clear space &amp; minimum size</h2><p>Keep clear space equal to the wordmark cap height on every side. Minimum: symbol 16 px / 5 mm, horizontal logo 96 px / 25 mm.</p>
<h2>Color</h2><div class="swatches">${swatches}</div>${scales}
<h2>Typography</h2><p>${kit.typography ? `${escapeText(kit.typography.family ?? kit.typography.fontId)} ${kit.typography.weight} — ${escapeText(kit.typography.license ?? '')}` : 'Outlined wordmark; no typeface required.'}</p>
${
  kit.originality
    ? `<h2>Originality check</h2><p>Approved with originality verdict <b>${escapeText(kit.originality.verdict)}</b> (confidence ${escapeText(kit.originality.confidence)})${kit.originality.acceptedRisk ? ', with the remaining risk explicitly accepted' : ''}.</p>${evidenceLines(
        kit,
      )
        .map((l) => `<p>${escapeText(l)}</p>`)
        .join('')}`
    : ''
}
${kit.notes?.length ? `<h2>Usage notes</h2><ul>${kit.notes.map((n) => `<li>${escapeText(n)}</li>`).join('')}</ul>` : ''}
<h2>Do not</h2><ul class="dont">${DONTS.map((d) => `<li>${escapeText(d)}</li>`).join('')}</ul>
</main></body></html>
`;
}
